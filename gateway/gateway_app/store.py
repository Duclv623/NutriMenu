"""PostgreSQL-only identity bridge and UI data absent from the Java services.

Never stores passwords, sessions, catalog rows or copies of editable meal plans.
"""

from contextlib import contextmanager
from threading import Lock

from psycopg.types.json import Jsonb


class TeamStore:
    def __init__(self, history):
        self.history = history
        self.ready = False
        self.lock = Lock()

    def initialize(self):
        with self.lock:
            if self.ready:
                return
            self.history.initialize()
            with self.history.connect() as db:
                db.execute(
                    "SELECT pg_advisory_xact_lock(hashtext(%s))",
                    ("nutriguide-team-bridge",),
                )
                db.execute("""CREATE TABLE IF NOT EXISTS team_identities (
                    account_id UUID PRIMARY KEY,
                    service_user_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000) UNIQUE NOT NULL
                )""")
                db.execute("""CREATE TABLE IF NOT EXISTS team_ui_state (
                    account_id UUID NOT NULL REFERENCES team_identities(account_id),
                    state_key TEXT NOT NULL, value JSONB NOT NULL,
                    PRIMARY KEY(account_id, state_key)
                )""")
                self.history.import_legacy(db)
            self.ready = True

    def service_id(self, account_id):
        self.initialize()
        with self.history.connect() as db:
            return db.execute(
                """INSERT INTO team_identities(account_id) VALUES (%s)
                ON CONFLICT(account_id) DO UPDATE SET account_id=EXCLUDED.account_id
                RETURNING service_user_id""",
                (account_id,),
            ).fetchone()[0]

    def get(self, account_id, key, default=None):
        self.initialize()
        with self.history.connect() as db:
            row = db.execute(
                "SELECT value FROM team_ui_state WHERE account_id=%s AND state_key=%s",
                (account_id, key),
            ).fetchone()
        return row[0] if row else default

    def put(self, account_id, key, value):
        self.initialize()
        with self.history.connect() as db:
            db.execute(
                """INSERT INTO team_ui_state(account_id,state_key,value) VALUES (%s,%s,%s)
                ON CONFLICT(account_id,state_key) DO UPDATE SET value=EXCLUDED.value""",
                (account_id, key, Jsonb(value)),
            )

    def check_in(self, account_id, entry=None, delete_id=None):
        """Serialize changes so two tabs cannot lose each other's check-ins."""
        self.initialize()
        with self.history.connect() as db:
            db.execute(
                "SELECT pg_advisory_xact_lock(hashtext(%s))",
                (str(account_id) + ":checkins",),
            )
            row = db.execute(
                "SELECT value FROM team_ui_state WHERE account_id=%s AND state_key='checkIns'",
                (account_id,),
            ).fetchone()
            entries = row[0] if row else []
            if delete_id:
                entries = [e for e in entries if e["id"] != delete_id]
            else:
                entries = [entry, *[e for e in entries if e["id"] != entry["id"]]][:1000]
            db.execute(
                """INSERT INTO team_ui_state(account_id,state_key,value) VALUES (%s,'checkIns',%s)
                ON CONFLICT(account_id,state_key) DO UPDATE SET value=EXCLUDED.value""",
                (account_id, Jsonb(entries)),
            )

    @contextmanager
    def operation(self, account_id):
        self.initialize()
        with self.history.connect() as db:
            db.execute(
                "SELECT pg_advisory_xact_lock(hashtext(%s))",
                ("team-write:" + str(account_id),),
            )
            yield
